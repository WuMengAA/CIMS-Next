/**
 * pg-bootstrap.mjs —— 在 stelarith 库内建一个隔离 schema `parity`，
 * 用「与 app 完全一致的 DDL」构建全部 42 张表，供数据 parity 验证使用。
 *
 * 设计原则：
 * - 零破坏：不触碰现有 public schema（那里是之前 parity 跑出来的残缺表），所有表落在 parity schema。
 * - 忠实：SCHEMA / class8 / stelarith_classes / login_attempts 的 DDL 文本直接从源码抽取，
 *   并套用与 db.ts 相同的 transformSchemaToPg（AUTOINCREMENT→IDENTITY、BLOB→BYTEA）。
 * - 幂等：CREATE TABLE IF NOT EXISTS + ADD COLUMN IF NOT EXISTS。
 *
 * 运行：node scripts/pg-bootstrap.mjs
 */
import { readFileSync } from "node:fs";
import { Client } from "pg";

// 从环境变量或 .env 读取 DATABASE_URL（绝不硬编码口令，避免密钥入库）。
function loadDbUrl() {
	if (process.env.PG_URL) return process.env.PG_URL;
	if (process.env.DATABASE_URL) return process.env.DATABASE_URL;
	const m = readFileSync(".env", "utf-8").match(/^DATABASE_URL=(.*)$/m);
	if (m) return m[1].trim().replace(/^["']|["']$/g, "");
	throw new Error("未找到 DATABASE_URL：请设置 PG_URL / DATABASE_URL，或在 .env 配置");
}
const PG_URL = loadDbUrl();
const NS = "parity";

function transformSchemaToPg(schema) {
	return schema
		.replace(/INTEGER\s+PRIMARY\s+KEY\s+AUTOINCREMENT/gi, "INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY")
		.replace(/\bBLOB\b/gi, "BYTEA");
}

const dbTs = readFileSync("src/lib/server/db.ts", "utf-8");
const schemaMatch = dbTs.match(/const SCHEMA = `([\s\S]*?)`;/);
if (!schemaMatch) throw new Error("db.ts 中未找到 SCHEMA 常量");
const schemaSql = transformSchemaToPg(schemaMatch[1]);

// class8 的 DDL 是整段 CLASS8_SCHEMA 模板字面量（含 CHECK(id=1) 这类带括号的列约束），
// 不能按 `)` 切分，必须整段抽取后整体翻译执行（与 SCHEMA 处理一致）。
const class8Ts = readFileSync("src/lib/server/class8/class8-db.ts", "utf-8");
const class8Match = class8Ts.match(/const CLASS8_SCHEMA = `([\s\S]*?)`;/);
if (!class8Match) throw new Error("class8-db.ts 中未找到 CLASS8_SCHEMA 常量");
const class8Sql = transformSchemaToPg(class8Match[1]);

const stelarithClasses = `CREATE TABLE IF NOT EXISTS stelarith_classes (
	class_id   TEXT PRIMARY KEY,
	name       TEXT NOT NULL,
	code       TEXT NOT NULL DEFAULT '',
	sort_order INTEGER NOT NULL DEFAULT 0,
	created_at TEXT NOT NULL,
	school_id  TEXT NOT NULL DEFAULT ''
);`;

const loginAttempts = `CREATE TABLE IF NOT EXISTS login_attempts (
	key          TEXT PRIMARY KEY,
	fail_count   INTEGER NOT NULL DEFAULT 0,
	locked_until TEXT NOT NULL DEFAULT '',
	last_fail_at TEXT NOT NULL DEFAULT ''
);`;

// 与 db.ts PgBackend.ensure() 中的列迁移块逐字一致（幂等 ADD COLUMN IF NOT EXISTS）。
const alters = `ALTER TABLE users            ADD COLUMN IF NOT EXISTS verified           INTEGER NOT NULL DEFAULT 0;
ALTER TABLE users            ADD COLUMN IF NOT EXISTS verify_token       TEXT    NOT NULL DEFAULT '';
ALTER TABLE users            ADD COLUMN IF NOT EXISTS verify_token_expires TEXT  NOT NULL DEFAULT '';
ALTER TABLE users            ADD COLUMN IF NOT EXISTS class_name         TEXT    NOT NULL DEFAULT '';
ALTER TABLE users            ADD COLUMN IF NOT EXISTS grade_name         TEXT    NOT NULL DEFAULT '';
ALTER TABLE users            ADD COLUMN IF NOT EXISTS xp                 INTEGER NOT NULL DEFAULT 0;
ALTER TABLE users            ADD COLUMN IF NOT EXISTS quota_bonus_bytes  INTEGER NOT NULL DEFAULT 0;
ALTER TABLE sessions         ADD COLUMN IF NOT EXISTS deadline           TEXT    NOT NULL DEFAULT '';
ALTER TABLE console_notices  ADD COLUMN IF NOT EXISTS classes            TEXT    NOT NULL DEFAULT '';
ALTER TABLE console_notices  ADD COLUMN IF NOT EXISTS channel            TEXT    NOT NULL DEFAULT '';
ALTER TABLE console_notices  ADD COLUMN IF NOT EXISTS type               TEXT    NOT NULL DEFAULT 'notice';
ALTER TABLE console_notices  ADD COLUMN IF NOT EXISTS flags              TEXT    NOT NULL DEFAULT '';
ALTER TABLE notice_deliveries ADD COLUMN IF NOT EXISTS reply             TEXT    NOT NULL DEFAULT '';
ALTER TABLE console_audit    ADD COLUMN IF NOT EXISTS prev_hash          TEXT    NOT NULL DEFAULT '';
ALTER TABLE console_audit    ADD COLUMN IF NOT EXISTS row_hash           TEXT    NOT NULL DEFAULT '';
UPDATE users SET verified = 1 WHERE status = 'active' AND verified = 0;`;

const client = new Client({ connectionString: PG_URL });
await client.connect();
await client.query(`CREATE SCHEMA IF NOT EXISTS ${NS};`);
await client.query(`SET search_path TO ${NS};`);

await client.query(schemaSql);
await client.query(alters);
await client.query(stelarithClasses);
await client.query(loginAttempts);
await client.query(class8Sql);
// class8 的 quote/subtitle/emoji/photos 由 class8-db.ts ensureClass8Schema 末尾的
// ensureColumn(ALTER TABLE ADD COLUMN) 补齐，基础 CLASS8_SCHEMA 不含它们。
// 忠实复刻这 4 个 ALTER，否则 parity 的 class8 表会缺列（与 PG 运行时行为一致）。
await client.query(`
	ALTER TABLE class8_profile ADD COLUMN IF NOT EXISTS quote TEXT NOT NULL DEFAULT '';
	ALTER TABLE class8_profile ADD COLUMN IF NOT EXISTS subtitle TEXT NOT NULL DEFAULT '';
	ALTER TABLE class8_groups ADD COLUMN IF NOT EXISTS emoji TEXT NOT NULL DEFAULT '';
	ALTER TABLE class8_events ADD COLUMN IF NOT EXISTS photos TEXT NOT NULL DEFAULT '[]';
`);

const res = await client.query(
	`SELECT table_name FROM information_schema.tables WHERE table_schema=$1 ORDER BY table_name`,
	[NS]
);
console.log(`[bootstrap] ${NS} schema 建表完成，共 ${res.rows.length} 张：`);
console.log(res.rows.map((r) => r.table_name).join("\n"));
await client.end();
