/**
 * pg-parity.mjs —— 数据 parity 验证（SQLite 生产库 ↔ PG parity schema）。
 *
 * 三道防线：
 * 1. 逐表 COUNT(*)：证明迁移无丢失、PG 计数正确。
 * 2. 逐行内容比对（容错相等）：证明每条记录的值在两种后端一致（含类型/二进制）。
 * 3. 复杂查询比对：用 app 真实的 SQL + 复刻的 translateToPg 在 PG 跑，
 *    与 SQLite 原句结果做多重集比对，覆盖 GROUP_CONCAT→string_agg、GROUP BY、
 *    COUNT(*)::int、SUM/COALESCE 等方言关键点。
 *
 * 只读：SQLite readOnly，PG 只 SELECT。
 * 运行：node scripts/pg-parity.mjs
 */
import { DatabaseSync } from "node:sqlite";
import { readFileSync } from "node:fs";
import { Client } from "pg";

const SQLITE_PATH = "content/stelarith.db";
// 从环境变量或 .env 读取 DATABASE_URL（绝不硬编码口令，避免密钥入库）。
function loadDbUrl() {
	if (process.env.PG_URL) return process.env.PG_URL;
	if (process.env.DATABASE_URL) return process.env.DATABASE_URL;
	const m = readFileSync(".env", "utf-8").match(/^DATABASE_URL=(.*)$/m);
	if (m) return m[1].trim().replace(/^["']|["']$/g, "");
	throw new Error("未找到 DATABASE_URL：请设置 PG_URL / DATABASE_URL，或在 .env 配置");
}
const PG_URL = loadDbUrl();
const NS = "parity";

// ── translateToPg：与 src/lib/server/db.ts 逐字一致（验证方言层） ──
function translateToPg(sql) {
	let out = "";
	let i = 0;
	let n = 0;
	let insertIgnore = false;
	while (i < sql.length) {
		const rest = sql.slice(i);
		if (sql[i] === "'") {
			let j = i + 1;
			while (j < sql.length) {
				if (sql[j] === "'") {
					if (sql[j + 1] === "'") {
						j += 2;
						continue;
					}
					break;
				}
				j++;
			}
			out += sql.slice(i, j + 1);
			i = j + 1;
			continue;
		}
		const ignore = rest.match(/^INSERT\s+OR\s+IGNORE\s+INTO/i);
		if (ignore) {
			out += "INSERT INTO";
			i += ignore[0].length;
			insertIgnore = true;
			continue;
		}
		const pragma = rest.match(/^PRAGMA\s+table_info\s*\(\s*(\w+)\s*\)/i);
		if (pragma) {
			out += `SELECT column_name AS name FROM information_schema.columns WHERE table_schema = current_schema() AND table_name = '${pragma[1]}' ORDER BY ordinal_position`;
			i += pragma[0].length;
			continue;
		}
		const ident = rest.match(/^INTEGER\s+PRIMARY\s+KEY\s+AUTOINCREMENT/i);
		if (ident) {
			out += "INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY";
			i += ident[0].length;
			continue;
		}
		if (/^GROUP_CONCAT\(/i.test(rest)) {
			const open = rest.indexOf("(");
			let depth = 0;
			let k = open;
			for (; k < rest.length; k++) {
				if (rest[k] === "(") depth++;
				else if (rest[k] === ")") {
					depth--;
					if (depth === 0) break;
				}
			}
			const inner = rest.slice(open + 1, k);
			let d2 = 0;
			let inS = false;
			let split = -1;
			for (let x = 0; x < inner.length; x++) {
				const c = inner[x];
				if (c === "'") inS = !inS;
				else if (!inS) {
					if (c === "(") d2++;
					else if (c === ")") d2--;
					else if (c === "," && d2 === 0) {
						split = x;
						break;
					}
				}
			}
			const expr = (split >= 0 ? inner.slice(0, split) : inner).trim();
			const sep = split >= 0 ? inner.slice(split + 1).trim() : "','";
			out += `string_agg(${expr}::text, ${sep})`;
			i += k + 1;
			continue;
		}
		const dt = rest.match(/^datetime\(\s*([^,()]+?)\s*,\s*'([+-])\s*(\d+)\s+([a-z]+)'\s*\)/i);
		if (dt) {
			out += `(${dt[1].trim()}::timestamp ${dt[2]} interval '${dt[3]} ${dt[4]}')`;
			i += dt[0].length;
			continue;
		}
		const cnt = rest.match(/^COUNT\(\s*\*\s*\)/i);
		if (cnt) {
			out += "COUNT(*)::int";
			i += cnt[0].length;
			continue;
		}
		if (sql[i] === "?") {
			out += "$" + ++n;
			i++;
			continue;
		}
		out += sql[i];
		i++;
	}
	return { text: out, insertIgnore };
}

function numish(v) {
	if (typeof v === "number") return v;
	if (typeof v === "string" && v.trim() !== "" && !Number.isNaN(Number(v))) return Number(v);
	return null;
}
function eq(a, b) {
	if (a === b) return true;
	if (a == null || b == null) return a == null && b == null;
	if (a instanceof Uint8Array || Buffer.isBuffer(a)) {
		const ba = Buffer.isBuffer(a) ? a : Buffer.from(a);
		const bb = Buffer.isBuffer(b) ? b : Buffer.from(b);
		return ba.equals(bb);
	}
	const na = numish(a);
	const nb = numish(b);
	if (na !== null && nb !== null) return na === nb;
	if (typeof a === "string" && typeof b === "string") return a === b;
	return false;
}
function rowKey(row) {
	const ks = Object.keys(row).sort();
	return ks
		.map((k) => {
			const v = row[k];
			const n = numish(v);
			const s = n !== null ? String(n) : typeof v === "string" ? v : Buffer.isBuffer(v) || v instanceof Uint8Array ? "buf" : JSON.stringify(v);
			return `${k}=${s}`;
		})
		.join("|");
}

// 多重集比对：把每行归一成 rowKey 并计数，比较两库是否为同一多重集（与行顺序/主键无关）。
function rowMultiset(rows, cols) {
	const m = new Map();
	for (const r of rows) {
		const o = {};
		for (const c of cols) o[c] = r[c];
		const k = rowKey(o);
		m.set(k, (m.get(k) || 0) + 1);
	}
	return m;
}

const sq = new DatabaseSync(SQLITE_PATH, { readOnly: true });
const pg = new Client({ connectionString: PG_URL });
await pg.connect();
await pg.query(`SET search_path TO ${NS};`);

const tables = sq
	.prepare("SELECT name FROM sqlite_master WHERE type='table' AND name NOT LIKE 'sqlite_%' ORDER BY name")
	.all()
	.map((r) => r.name);

async function getPk(t) {
	const r = await pg.query(
		`SELECT a.attname FROM pg_index i JOIN pg_attribute a ON a.attrelid=i.indrelid AND a.attnum=ANY(i.indkey)
		 WHERE i.indrelid=($1||'.'||$2)::regclass AND i.indisprimary ORDER BY a.attnum`,
		[NS, t]
	);
	return r.rows.map((x) => x.attname);
}

// ── 第 1+2 道：逐表 COUNT + 逐行内容比对 ──
let passCount = 0;
const tableFails = [];
console.log("=== 逐表 parity（COUNT + 内容） ===");
for (const t of tables) {
	const cSq = sq.prepare(`SELECT COUNT(*) AS n FROM "${t}"`).get().n;
	const cPg = (await pg.query(`SELECT COUNT(*)::int AS n FROM "${t}"`)).rows[0].n;
	let ok = cSq === cPg;
	let detail = "";
	if (ok && cSq > 0) {
		const pk = await getPk(t);
		const ob = pk.length ? `ORDER BY ${pk.map((c) => `"${c}"`).join(", ")}` : "";
		const rSq = sq.prepare(`SELECT * FROM "${t}" ${ob}`).all();
		const rPg = (await pg.query(`SELECT * FROM "${t}" ${ob}`)).rows;
		const cols = Object.keys(rSq[0]);
		const pgKeys = new Set(Object.keys(rPg[0] || {}));
		const missingInPg = cols.filter((c) => !pgKeys.has(c));
		const ms = rowMultiset(rSq, cols);
		const mp = rowMultiset(rPg, cols);
		let mismatch = 0;
		const sample = [];
		for (const [k, v] of ms) if (mp.get(k) !== v) {
			mismatch++;
			if (sample.length < 5) sample.push(`${k} x${v} vs pg x${mp.get(k) || 0}`);
		}
		for (const [k, v] of mp) if (!ms.has(k)) {
			mismatch++;
			if (sample.length < 5) sample.push(`pg-only ${k} x${v}`);
		}
		ok = mismatch === 0 && missingInPg.length === 0;
		detail = ok
			? `rows=${cSq}`
			: `mismatch=${mismatch}${missingInPg.length ? `; missingInPg=${missingInPg.join(",")}` : ""}; ` + sample.join("; ");
	} else {
		detail = `sqlite=${cSq} pg=${cPg}`;
	}
	if (ok) passCount++;
	else tableFails.push(`${t}: ${detail}`);
	console.log(`${ok ? "OK " : "XX "} ${t}\t${detail}`);
}

// ── 第 3 道：复杂查询比对（app 真实 SQL + translateToPg）──
console.log("\n=== 复杂查询 parity（SQLite 原句 ↔ PG 翻译句） ===");
const queries = [
	{
		name: "onlineUsers(GROUP_CONCAT→string_agg)",
		sql: `SELECT u.username, u.display_name, u.role, u.avatar,
		             MAX(s.last_seen_at) AS last_seen, COUNT(*) AS session_count,
		             GROUP_CONCAT(DISTINCT s.ip) AS ips
		        FROM sessions s JOIN users u ON u.id = s.user_id
		       WHERE s.last_seen_at >= ?
		       GROUP BY u.id
		       ORDER BY last_seen DESC`,
		params: [new Date(Date.now() - 365 * 24 * 3600 * 1000).toISOString()],
		// app 端 onlineUsers 实际用 String(r.ips||"").split(",").filter(Boolean) 消费 ips，
		// 空串会被过滤；故按 app 用法归一化后再比（消除 GROUP_CONCAT/string_agg 空串排序差异）。
		norm: (r) => ({ ...r, ips: String(r.ips || "").split(",").filter(Boolean).join(",") })
	},
	{
		name: "topActiveUsers(GROUP BY 修复)",
		sql: `SELECT a.username AS username,
		             COALESCE(u.display_name, a.username) AS display_name,
		             COUNT(*) AS count
		        FROM activities a LEFT JOIN users u ON u.id = a.user_id
		       WHERE a.created_at >= ? AND a.user_id IS NOT NULL
		       GROUP BY a.user_id, a.username, u.display_name
		       ORDER BY count DESC, username ASC LIMIT ?`,
		params: [new Date(Date.now() - 365 * 24 * 3600 * 1000).toISOString(), 8]
	},
	{
		name: "attachmentQuota(SUM/COALESCE)",
		sql: `SELECT COALESCE(SUM(bytes),0) AS used, COUNT(*) AS n FROM attachments WHERE owner_id = ?`,
		params: [sq.prepare("SELECT id FROM users LIMIT 1").get()?.id ?? 1]
	},
	{
		name: "dailyActivities(substr+COUNT)",
		sql: `SELECT substr(created_at, 1, 10) AS d, COUNT(*) AS n FROM activities WHERE created_at >= ? GROUP BY d ORDER BY d ASC`,
		params: [new Date(Date.now() - 60 * 24 * 3600 * 1000).toISOString()]
	},
	{
		name: "listActivities(WHERE+COUNT)",
		sql: `SELECT COUNT(*) AS n FROM activities WHERE action = ?`,
		params: ["login"]
	}
];

const qFails = [];
for (const q of queries) {
	const rSq = sq.prepare(q.sql).all(...q.params);
	const t = translateToPg(q.sql);
	const rPg = (await pg.query(t.text, q.params)).rows;
	const mk = (arr) => {
		const m = new Map();
		for (const r of arr) {
			const k = rowKey(q.norm ? q.norm(r) : r);
			m.set(k, (m.get(k) || 0) + 1);
		}
		return m;
	};
	const ms = mk(rSq);
	const mp = mk(rPg);
	let ok = ms.size === mp.size;
	const diffs = [];
	for (const [k, v] of ms) if (mp.get(k) !== v) diffs.push(`- ${k} x${v} vs pg x${mp.get(k) || 0}`);
	for (const [k, v] of mp) if (!ms.has(k)) diffs.push(`+ ${k} x${v}`);
	if (diffs.length) {
		ok = false;
		qFails.push(`${q.name}: ${diffs.slice(0, 5).join("; ")}`);
	}
	console.log(`${ok ? "OK " : "XX "} ${q.name}\t(sqlite=${rSq.length} pg=${rPg.length})${ok ? "" : "\n     " + diffs.slice(0, 5).join("\n     ")}`);
}

// ── 汇总 ──
console.log("\n=== 汇总 ===");
console.log(`逐表：通过 ${passCount}/${tables.length}，失败 ${tableFails.length}`);
console.log(`复杂查询：通过 ${queries.length - qFails.length}/${queries.length}，失败 ${qFails.length}`);
if (tableFails.length) console.log("逐表失败：\n" + tableFails.join("\n"));
if (qFails.length) console.log("查询失败：\n" + qFails.join("\n"));
const allOk = tableFails.length === 0 && qFails.length === 0;
console.log(allOk ? "\n[PARITY] 全部通过 ✅" : "\n[PARITY] 存在差异 ⚠️");

await pg.end();
sq.close();
